/**
 * Generate the browser-safe DejaVu font byte module the PDF writer falls back
 * to for characters the 14 standard PDF fonts cannot encode — Greek, Cyrillic,
 * Vietnamese, arrows, math, box drawing and common symbols.
 *
 * The fonts come unmodified from the pinned `dejavu-fonts-ttf` devDependency,
 * whose license the formats build copies into THIRD_PARTY_LICENSES.txt. Like
 * the Font Awesome module, the bytes travel as base64 in plain JavaScript,
 * because importing a binary asset is bundler-dependent. The PDF writer loads
 * this module with a dynamic import, so only a document that needs it pays
 * for it.
 */

import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import url from 'node:url';

const repoRoot = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const formatsDir = path.join(repoRoot, 'packages', 'formats');
const require = createRequire(path.join(formatsDir, 'package.json'));
const fontPackageDir = path.dirname(require.resolve('dejavu-fonts-ttf/package.json'));
const fontVersion = JSON.parse(
  fs.readFileSync(path.join(fontPackageDir, 'package.json'), 'utf8'),
).version;
const outPath = path.join(formatsDir, 'src', 'assets', 'unicodeFontData.generated.ts');

const fonts = [
  ['regular', 'DejaVuSans.ttf'],
  ['bold', 'DejaVuSans-Bold.ttf'],
  ['mono', 'DejaVuSansMono.ttf'],
];

const encoded = fonts.map(([face, filename]) => [
  face,
  fs.readFileSync(path.join(fontPackageDir, 'ttf', filename)).toString('base64'),
]);

const source = `/**
 * GENERATED by scripts/generate-unicode-font-data.mjs.
 * DejaVu Sans ${fontVersion} (dejavu-fonts-ttf), unmodified; Bitstream Vera and
 * DejaVu licenses. Imported on demand by the PDF writer.
 */

function decodeBase64(value: string): Uint8Array {
  const decoded = atob(value);
  const bytes = new Uint8Array(decoded.length);
  for (let index = 0; index < decoded.length; index++) {
    bytes[index] = decoded.charCodeAt(index);
  }
  return bytes;
}

${encoded.map(([face, base64]) => `const ${face}Base64 =\n  '${base64}';`).join('\n\n')}

/** DejaVu Sans regular and bold, and DejaVu Sans Mono, as TrueType bytes. */
export function dejaVuFontData(): { regular: Uint8Array; bold: Uint8Array; mono: Uint8Array } {
  return {
${fonts.map(([face]) => `    ${face}: decodeBase64(${face}Base64),`).join('\n')}
  };
}
`;

fs.writeFileSync(outPath, source, 'utf8');
console.log(`Wrote ${outPath}`);
