/**
 * Generate the browser-safe font byte modules the PDF writer falls back to for
 * characters the 14 standard PDF fonts cannot encode:
 *
 * - DejaVu Sans — Greek, Cyrillic, Vietnamese, arrows, math, box drawing and
 *   common symbols;
 * - Noto Emoji (monochrome) — emoji, including ZWJ sequences, flags and
 *   keycaps;
 * - Noto Sans SC — Chinese, plus the kana and kanji Japanese needs;
 * - Noto Sans KR — Korean.
 *
 * The fonts come unmodified from pinned devDependencies, whose licenses the
 * formats build copies into THIRD_PARTY_LICENSES.txt. Like the Font Awesome
 * module, the bytes travel as base64 in plain JavaScript, because importing a
 * binary asset is bundler-dependent. Each font is its own module, which the
 * PDF writer loads with a dynamic import, so only a document with text in
 * that font's scripts pays for it.
 */

import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import url from 'node:url';

const repoRoot = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const formatsDir = path.join(repoRoot, 'packages', 'formats');
const require = createRequire(path.join(formatsDir, 'package.json'));
const assetsDir = path.join(formatsDir, 'src', 'assets');

function packageDir(name) {
  return path.dirname(require.resolve(`${name}/package.json`));
}

function packageVersion(name) {
  return JSON.parse(fs.readFileSync(path.join(packageDir(name), 'package.json'), 'utf8')).version;
}

function base64Of(name, ...file) {
  return fs.readFileSync(path.join(packageDir(name), ...file)).toString('base64');
}

const decoder = `function decodeBase64(value: string): Uint8Array {
  const decoded = atob(value);
  const bytes = new Uint8Array(decoded.length);
  for (let index = 0; index < decoded.length; index++) {
    bytes[index] = decoded.charCodeAt(index);
  }
  return bytes;
}`;

function write(filename, source) {
  const outPath = path.join(assetsDir, filename);
  fs.writeFileSync(outPath, source, 'utf8');
  console.log(`Wrote ${outPath}`);
}

const dejaVuFonts = [
  ['regular', 'DejaVuSans.ttf'],
  ['bold', 'DejaVuSans-Bold.ttf'],
  ['mono', 'DejaVuSansMono.ttf'],
];

write(
  'unicodeFontData.generated.ts',
  `/**
 * GENERATED by scripts/generate-unicode-font-data.mjs.
 * DejaVu Sans ${packageVersion('dejavu-fonts-ttf')} (dejavu-fonts-ttf), unmodified; Bitstream Vera and
 * DejaVu licenses. Imported on demand by the PDF writer.
 */

${decoder}

${dejaVuFonts
  .map(
    ([face, filename]) =>
      `const ${face}Base64 =\n  '${base64Of('dejavu-fonts-ttf', 'ttf', filename)}';`,
  )
  .join('\n\n')}

/** DejaVu Sans regular and bold, and DejaVu Sans Mono, as TrueType bytes. */
export function dejaVuFontData(): { regular: Uint8Array; bold: Uint8Array; mono: Uint8Array } {
  return {
${dejaVuFonts.map(([face]) => `    ${face}: decodeBase64(${face}Base64),`).join('\n')}
  };
}
`,
);

/** One Noto face from an `@expo-google-fonts` package, as its own module. */
const notoFonts = [
  {
    filename: 'emojiFontData.generated.ts',
    packageName: '@expo-google-fonts/noto-emoji',
    file: ['400Regular', 'NotoEmoji_400Regular.ttf'],
    family: 'Noto Emoji Regular (monochrome)',
    exportName: 'notoEmojiFontData',
  },
  {
    filename: 'cjkFontData.generated.ts',
    packageName: '@expo-google-fonts/noto-sans-sc',
    file: ['400Regular', 'NotoSansSC_400Regular.ttf'],
    family: 'Noto Sans SC Regular',
    exportName: 'notoSansScFontData',
  },
  {
    filename: 'hangulFontData.generated.ts',
    packageName: '@expo-google-fonts/noto-sans-kr',
    file: ['400Regular', 'NotoSansKR_400Regular.ttf'],
    family: 'Noto Sans KR Regular',
    exportName: 'notoSansKrFontData',
  },
];

for (const font of notoFonts) {
  write(
    font.filename,
    `/**
 * GENERATED by scripts/generate-unicode-font-data.mjs.
 * ${font.family} (${font.packageName} ${packageVersion(font.packageName)}), unmodified;
 * SIL Open Font License 1.1. Imported on demand by the PDF writer.
 */

${decoder}

const fontBase64 =
  '${base64Of(font.packageName, ...font.file)}';

/** ${font.family}, as TrueType bytes. */
export function ${font.exportName}(): Uint8Array {
  return decodeBase64(fontBase64);
}
`,
  );
}
