/**
 * Generate the browser-safe Font Awesome OpenType byte module used by formats.
 *
 * The raw desktop fonts remain checked in for licensing/provenance. Importing
 * a binary asset directly is bundler-dependent (esbuild returns bytes while
 * Vite commonly returns a URL), so exporters consume deterministic base64
 * decoded by this generated pure-JavaScript module instead.
 */

import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const repoRoot = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const fontsDir = path.join(repoRoot, 'packages', 'formats', 'src', 'assets', 'fonts');
const outPath = path.join(
  repoRoot,
  'packages',
  'formats',
  'src',
  'assets',
  'fontAwesomeFontData.generated.ts',
);

const fonts = [
  ['fontAwesomeBrandsData', 'Font Awesome 7 Brands-Regular-400.otf'],
  ['fontAwesomeRegularData', 'Font Awesome 7 Free-Regular-400.otf'],
  ['fontAwesomeSolidData', 'Font Awesome 7 Free-Solid-900.otf'],
];

const encoded = fonts.map(([name, filename]) => [
  name,
  fs.readFileSync(path.join(fontsDir, filename)).toString('base64'),
]);

const source = `/**
 * GENERATED by scripts/generate-fontawesome-font-data.mjs.
 * Font Awesome Free 7.2.0 desktop font bytes (SIL OFL 1.1).
 */

function decodeBase64(value: string): Uint8Array {
  const decoded = atob(value);
  const bytes = new Uint8Array(decoded.length);
  for (let index = 0; index < decoded.length; index++) {
    bytes[index] = decoded.charCodeAt(index);
  }
  return bytes;
}

${encoded
  .map(([name, base64]) => `export const ${name} = decodeBase64(\n  '${base64}',\n);`)
  .join('\n\n')}
`;

fs.writeFileSync(outPath, source, 'utf8');
console.log(`Wrote ${outPath}`);
